/**
 * imx686_power_on() - Sensor power on sequence
 * @dev: pointer to i2c device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_power_on(struct device *dev)
{
	struct v4l2_subdev *sd = dev_get_drvdata(dev);
	struct imx686 *imx686 = to_imx686(sd);
	int ret;

	gpiod_set_value_cansleep(imx686->enable_gpio, 1);
	usleep_range(1200, 2000);

	ret = regulator_bulk_enable(ARRAY_SIZE(imx686_supply_names),
				imx686->supplies);
	if (ret < 0) {
		dev_err(dev, "failed to enable regulators\n");
		return ret;
	}

	ret = clk_prepare_enable(imx686->inclk);
	if (ret) {
		dev_err(imx686->dev, "fail to enable inclk\n");
		goto error_reset;
	}

	gpiod_set_value_cansleep(imx686->reset_gpio, 0);
	usleep_range(7200, 8000);

	return 0;

error_reset:
	regulator_bulk_disable(ARRAY_SIZE(imx686_supply_names),
				imx686->supplies);
	gpiod_set_value_cansleep(imx686->enable_gpio, 0);

	return ret;
}

/**
 * imx686_power_off() - Sensor power off sequence
 * @dev: pointer to i2c device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_power_off(struct device *dev)
{
	struct v4l2_subdev *sd = dev_get_drvdata(dev);
	struct imx686 *imx686 = to_imx686(sd);

	gpiod_set_value_cansleep(imx686->reset_gpio, 1);
	usleep_range(1200, 2000);

	clk_disable_unprepare(imx686->inclk);

	regulator_bulk_disable(ARRAY_SIZE(imx686_supply_names),
				imx686->supplies);

	gpiod_set_value_cansleep(imx686->enable_gpio, 0);
	usleep_range(1200, 2000);

	return 0;
}

/**
 * imx686_init_controls() - Initialize sensor subdevice controls
 * @imx686: pointer to imx686 device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_init_controls(struct imx686 *imx686)
{
	struct v4l2_ctrl_handler *ctrl_hdlr = &imx686->ctrl_handler;
	const struct imx686_mode *mode = imx686->cur_mode;
	u32 lpfr;
	int ret;

	ret = v4l2_ctrl_handler_init(ctrl_hdlr, 6);
	if (ret)
		return ret;

	/* Serialize controls with sensor device */
	ctrl_hdlr->lock = &imx686->mutex;

	/* Initialize exposure and gain */
	lpfr = mode->vblank + mode->height;
	imx686->exp_ctrl = v4l2_ctrl_new_std(ctrl_hdlr,
					     &imx686_ctrl_ops,
					     V4L2_CID_EXPOSURE,
					     IMX686_EXPOSURE_MIN,
					     lpfr - IMX686_EXPOSURE_OFFSET,
					     IMX686_EXPOSURE_STEP,
					     IMX686_EXPOSURE_DEFAULT);

	imx686->again_ctrl = v4l2_ctrl_new_std(ctrl_hdlr,
					       &imx686_ctrl_ops,
					       V4L2_CID_ANALOGUE_GAIN,
					       IMX686_AGAIN_MIN,
					       IMX686_AGAIN_MAX,
					       IMX686_AGAIN_STEP,
					       IMX686_AGAIN_DEFAULT);

	v4l2_ctrl_cluster(2, &imx686->exp_ctrl);

	imx686->vblank_ctrl = v4l2_ctrl_new_std(ctrl_hdlr,
						&imx686_ctrl_ops,
						V4L2_CID_VBLANK,
						mode->vblank_min,
						mode->vblank_max,
						1, mode->vblank);

	/* Read only controls */
	imx686->pclk_ctrl = v4l2_ctrl_new_std(ctrl_hdlr,
					      &imx686_ctrl_ops,
					      V4L2_CID_PIXEL_RATE,
					      mode->pclk, mode->pclk,
					      1, mode->pclk);

	imx686->link_freq_ctrl = v4l2_ctrl_new_int_menu(ctrl_hdlr,
							&imx686_ctrl_ops,
							V4L2_CID_LINK_FREQ,
							ARRAY_SIZE(link_freq) -
							1,
							mode->link_freq_idx,
							link_freq);
	if (imx686->link_freq_ctrl)
		imx686->link_freq_ctrl->flags |= V4L2_CTRL_FLAG_READ_ONLY;

	imx686->hblank_ctrl = v4l2_ctrl_new_std(ctrl_hdlr,
						&imx686_ctrl_ops,
						V4L2_CID_HBLANK,
						IMX686_REG_MIN,
						IMX686_REG_MAX,
						1, mode->hblank);
	if (imx686->hblank_ctrl)
		imx686->hblank_ctrl->flags |= V4L2_CTRL_FLAG_READ_ONLY;

	if (ctrl_hdlr->error) {
		dev_err(imx686->dev, "control init failed: %d\n",
			ctrl_hdlr->error);
		v4l2_ctrl_handler_free(ctrl_hdlr);
		return ctrl_hdlr->error;
	}

	imx686->sd.ctrl_handler = ctrl_hdlr;

	return 0;
}

/**
 * imx686_probe() - I2C client device binding
 * @client: pointer to i2c client device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_probe(struct i2c_client *client)
{
	struct imx686 *imx686;
	int ret;

	imx686 = devm_kzalloc(&client->dev, sizeof(*imx686), GFP_KERNEL);
	if (!imx686)
		return -ENOMEM;

	imx686->dev = &client->dev;

	/* Initialize subdev */
	v4l2_i2c_subdev_init(&imx686->sd, client, &imx686_subdev_ops);
   imx686->sd.internal_ops = &imx686_internal_ops;
	dev_err(imx686->dev, "subdev init passed!\n");


	ret = imx686_parse_hw_config(imx686);
	if (ret) {
		dev_err(imx686->dev, "HW configuration is not supported\n");
		return ret;
	}
	dev_err(imx686->dev, "parse hw config passed!\n");

	mutex_init(&imx686->mutex);

	ret = imx686_power_on(imx686->dev);
	if (ret) {
		dev_err(imx686->dev, "failed to power-on the sensor\n");
		goto error_mutex_destroy;
	}
	dev_err(imx686->dev, "power on passed!\n");

	/* Check module identity */
	ret = imx686_detect(imx686);
	if (ret) {
		dev_err(imx686->dev, "failed to find sensor: %d\n", ret);
		goto error_power_off;
	}
	dev_err(imx686->dev, "detect passed!\n");

	/* Set default mode to max resolution */
	imx686->cur_mode = &supported_mode;
	imx686->vblank = imx686->cur_mode->vblank;

	ret = imx686_init_controls(imx686);
	if (ret) {
		dev_err(imx686->dev, "failed to init controls: %d\n", ret);
		goto error_power_off;
	}

	dev_err(imx686->dev, "init ctrl passed!\n");

	/* Initialize subdev */
	imx686->sd.flags |= V4L2_SUBDEV_FL_HAS_DEVNODE;
	imx686->sd.entity.function = MEDIA_ENT_F_CAM_SENSOR;

	/* Initialize source pad */
	imx686->pad.flags = MEDIA_PAD_FL_SOURCE;
	ret = media_entity_pads_init(&imx686->sd.entity, 1, &imx686->pad);
	if (ret) {
		dev_err(imx686->dev, "failed to init entity pads: %d\n", ret);
		goto error_handler_free;
	}
	dev_err(imx686->dev, "media_entity_pads_init passed!\n");

	ret = v4l2_async_register_subdev_sensor(&imx686->sd);
	if (ret < 0) {
		dev_err(imx686->dev,
			"failed to register async subdev: %d\n", ret);
		goto error_media_entity;
	}
	dev_err(imx686->dev, "async reg passed!\n");

	pm_runtime_set_active(imx686->dev);
	pm_runtime_enable(imx686->dev);
	pm_runtime_idle(imx686->dev);

	dev_err(imx686->dev, "Probe success\n");
	return 0;

error_media_entity:
	media_entity_cleanup(&imx686->sd.entity);
error_handler_free:
	v4l2_ctrl_handler_free(imx686->sd.ctrl_handler);
error_power_off:
	imx686_power_off(imx686->dev);
error_mutex_destroy:
	mutex_destroy(&imx686->mutex);

	dev_err(imx686->dev, "Probe fail %d\n", ret);
	return ret;
}

/**
 * imx686_remove() - I2C client device unbinding
 * @client: pointer to I2C client device
 *
 * Return: 0 if successful, error code otherwise.
 */
static void imx686_remove(struct i2c_client *client)
{
	struct v4l2_subdev *sd = i2c_get_clientdata(client);
	struct imx686 *imx686 = to_imx686(sd);

	v4l2_async_unregister_subdev(sd);
	media_entity_cleanup(&sd->entity);
	v4l2_ctrl_handler_free(sd->ctrl_handler);

	pm_runtime_disable(&client->dev);
	if (!pm_runtime_status_suspended(&client->dev))
		imx686_power_off(&client->dev);
	pm_runtime_set_suspended(&client->dev);

	mutex_destroy(&imx686->mutex);
}

