/* Streaming Mode */
#define IMX686_REG_MODE_SELECT	0x0100
#define IMX686_MODE_STANDBY	0x00
#define IMX686_MODE_STREAMING	0x01

/* Lines per frame */
#define IMX686_REG_LPFR		0x0340

/* Chip ID */
#define IMX686_REG_ID		0x0016
#define IMX686_ID		0x0686

/* Exposure control */
#define IMX686_REG_EXPOSURE_CIT	0x0202
#define IMX686_EXPOSURE_MIN	8
#define IMX686_EXPOSURE_OFFSET	22
#define IMX686_EXPOSURE_STEP	1
#define IMX686_EXPOSURE_DEFAULT	0x0648

/* Analog gain control */
#define IMX686_REG_AGAIN	0x0204
#define IMX686_AGAIN_MIN	0
#define IMX686_AGAIN_MAX	978
#define IMX686_AGAIN_STEP	1
#define IMX686_AGAIN_DEFAULT	0

/* Group hold register */
#define IMX686_REG_HOLD		0x0104

/* Input clock rate */
// #define IMX686_INCLK_RATE	24000000
#define IMX686_INCLK_RATE	19200000

/* CSI2 HW configuration */
#define IMX686_LINK_FREQ	952000000
#define IMX686_NUM_DATA_LANES	4
#define IMX686_CPHY_NUM_DATA_LANES	3

#define IMX686_REG_CSI_SIG_MODE	0x0111
#define IMX686_CSI_SIG_DPHY	0x02
#define IMX686_CSI_SIG_CPHY	0x03

/* DPHY VC id range 0-3d
   CPHY VC id range 0-31d */
#define IMX686_REG_CSI_CH_ID	0x0110

#define IMX686_REG_MIN		0x00
#define IMX686_REG_MAX		0xffff

#define IMX686_REG_FRM_CNT	0x0005

/**
 * struct imx686_reg - imx686 sensor register
 * @address: Register address
 * @val: Register value
 */
struct imx686_reg {
	u16 address;
	u8 val;
};

/**
 * struct imx686_reg_list - imx686 sensor register list
 * @num_of_regs: Number of registers in the list
 * @regs: Pointer to register list
 */
struct imx686_reg_list {
	u32 num_of_regs;
	const struct imx686_reg *regs;
};

/**
 * struct imx686_mode - imx686 sensor mode structure
 * @width: Frame width
 * @height: Frame height
 * @code: Format code
 * @hblank: Horizontal blanking in lines
 * @vblank: Vertical blanking in lines
 * @vblank_min: Minimum vertical blanking in lines
 * @vblank_max: Maximum vertical blanking in lines
 * @pclk: Sensor pixel clock
 * @link_freq_idx: Link frequency index
 * @reg_list: Register list for sensor mode
 */
struct imx686_mode {
	u32 width;
	u32 height;
	u32 code;
	u32 hblank;
	u32 vblank;
	u32 vblank_min;
	u32 vblank_max;
	u64 pclk;
	u32 link_freq_idx;
	struct imx686_reg_list reg_list;
};


static const char * const imx686_supply_names[] = {
       "dovdd",        /* Digital I/O power */
       "avdd",         /* Analog power */
       "dvdd",         /* Digital core power */
};

/**
 * struct imx686 - imx686 sensor device structure
 * @dev: Pointer to generic device
 * @client: Pointer to i2c client
 * @sd: V4L2 sub-device
 * @pad: Media pad. Only one pad supported
 * @reset_gpio: Sensor reset gpio
 * @inclk: Sensor input clock
 * @supplies: Regulator supplies
 * @ctrl_handler: V4L2 control handler
 * @link_freq_ctrl: Pointer to link frequency control
 * @pclk_ctrl: Pointer to pixel clock control
 * @hblank_ctrl: Pointer to horizontal blanking control
 * @vblank_ctrl: Pointer to vertical blanking control
 * @exp_ctrl: Pointer to exposure control
 * @again_ctrl: Pointer to analog gain control
 * @vblank: Vertical blanking in lines
 * @cur_mode: Pointer to current selected sensor mode
 * @mutex: Mutex for serializing sensor controls
 * @streaming: Flag indicating streaming state
 */
struct imx686 {
	struct device *dev;
	struct i2c_client *client;
	struct v4l2_subdev sd;
	struct media_pad pad;
	struct gpio_desc *reset_gpio;
	struct gpio_desc *enable_gpio;
	struct clk *inclk;
	struct regulator_bulk_data supplies[ARRAY_SIZE(imx686_supply_names)];
	enum v4l2_mbus_type bus_type;
	struct v4l2_ctrl_handler ctrl_handler;
	struct v4l2_ctrl *link_freq_ctrl;
	struct v4l2_ctrl *pclk_ctrl;
	struct v4l2_ctrl *hblank_ctrl;
	struct v4l2_ctrl *vblank_ctrl;
	struct {
		struct v4l2_ctrl *exp_ctrl;
		struct v4l2_ctrl *again_ctrl;
	};
	u32 vblank;
	const struct imx686_mode *cur_mode;
	struct mutex mutex;
	bool streaming;
};

static const s64 link_freq[] = {
	IMX686_LINK_FREQ,
};

