/**
 * imx686_enum_frame_size() - Enumerate V4L2 sub-device frame sizes
 * @sd: pointer to imx686 V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 * @fsize: V4L2 sub-device size enumeration need to be filled
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_enum_frame_size(struct v4l2_subdev *sd,
				  struct v4l2_subdev_state *sd_state,
				  struct v4l2_subdev_frame_size_enum *fsize)
{
	if (fsize->index > 0)
		return -EINVAL;

	if (fsize->code != supported_mode.code)
		return -EINVAL;

	fsize->min_width = supported_mode.width;
	fsize->max_width = fsize->min_width;
	fsize->min_height = supported_mode.height;
	fsize->max_height = fsize->min_height;

	return 0;
}

/**
 * imx686_fill_pad_format() - Fill subdevice pad format
 *                            from selected sensor mode
 * @imx686: pointer to imx686 device
 * @mode: pointer to imx686_mode sensor mode
 * @fmt: V4L2 sub-device format need to be filled
 */
static void imx686_fill_pad_format(struct imx686 *imx686,
				   const struct imx686_mode *mode,
				   struct v4l2_subdev_format *fmt)
{
	fmt->format.width = mode->width;
	fmt->format.height = mode->height;
	fmt->format.code = mode->code;
	fmt->format.field = V4L2_FIELD_NONE;
	fmt->format.colorspace = V4L2_COLORSPACE_RAW;
	fmt->format.ycbcr_enc = V4L2_YCBCR_ENC_DEFAULT;
	fmt->format.quantization = V4L2_QUANTIZATION_DEFAULT;
	fmt->format.xfer_func = V4L2_XFER_FUNC_NONE;
}

/**
 * imx686_get_pad_format() - Get subdevice pad format
 * @sd: pointer to imx686 V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 * @fmt: V4L2 sub-device format need to be set
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_get_pad_format(struct v4l2_subdev *sd,
				 struct v4l2_subdev_state *sd_state,
				 struct v4l2_subdev_format *fmt)
{
	struct imx686 *imx686 = to_imx686(sd);

	mutex_lock(&imx686->mutex);

	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
		struct v4l2_mbus_framefmt *framefmt;

		framefmt = v4l2_subdev_state_get_format(sd_state, fmt->pad);
		fmt->format = *framefmt;
	} else {
		imx686_fill_pad_format(imx686, imx686->cur_mode, fmt);
	}

	mutex_unlock(&imx686->mutex);

	return 0;
}

/**
 * imx686_set_pad_format() - Set subdevice pad format
 * @sd: pointer to imx686 V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 * @fmt: V4L2 sub-device format need to be set
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_set_pad_format(struct v4l2_subdev *sd,
				 struct v4l2_subdev_state *sd_state,
				 struct v4l2_subdev_format *fmt)
{
	struct imx686 *imx686 = to_imx686(sd);
	const struct imx686_mode *mode;
	int ret = 0;

	mutex_lock(&imx686->mutex);

	mode = &supported_mode;
	imx686_fill_pad_format(imx686, mode, fmt);

	if (fmt->which == V4L2_SUBDEV_FORMAT_TRY) {
		struct v4l2_mbus_framefmt *framefmt;

		framefmt = v4l2_subdev_state_get_format(sd_state, fmt->pad);
		*framefmt = fmt->format;
	} else {
		ret = imx686_update_controls(imx686, mode);
		if (!ret)
			imx686->cur_mode = mode;
	}

	mutex_unlock(&imx686->mutex);

	return ret;
}

/**
 * imx686_init_pad_cfg() - Initialize sub-device pad configuration
 * @sd: pointer to imx686 V4L2 sub-device structure
 * @sd_state: V4L2 sub-device configuration
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_init_pad_cfg(struct v4l2_subdev *sd,
			       struct v4l2_subdev_state *sd_state)
{
	struct imx686 *imx686 = to_imx686(sd);
	struct v4l2_subdev_format fmt = { 0 };

	fmt.which = sd_state ? V4L2_SUBDEV_FORMAT_TRY : V4L2_SUBDEV_FORMAT_ACTIVE;
	imx686_fill_pad_format(imx686, &supported_mode, &fmt);

	return imx686_set_pad_format(sd, sd_state, &fmt);
}

/**
 * imx686_start_streaming() - Start sensor stream
 * @imx686: pointer to imx686 device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_start_streaming(struct imx686 *imx686)
{
	const struct imx686_reg_list *reg_list;
	int ret;

	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);

	/* Write sensor mode registers */
	reg_list = &imx686->cur_mode->reg_list;
	ret = imx686_write_regs(imx686, reg_list->regs,
				reg_list->num_of_regs);
	if (ret) {
		dev_err(imx686->dev, "fail to write initial registers\n");
		return ret;
	}

	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);

	/* Setup handler will write actual exposure and gain */
	ret =  __v4l2_ctrl_handler_setup(imx686->sd.ctrl_handler);
	if (ret) {
		dev_err(imx686->dev, "fail to setup handler\n");
		return ret;
	}
	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);

	/* Delay is required before streaming*/
	usleep_range(7400, 8000);

	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
	/* Start streaming */
	ret = imx686_write_reg(imx686, IMX686_REG_MODE_SELECT,
			       1, IMX686_MODE_STREAMING);
	if (ret) {
		dev_err(imx686->dev, "fail to start streaming\n");
		return ret;
	}

	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
	return 0;
}

/**
 * imx686_stop_streaming() - Stop sensor stream
 * @imx686: pointer to imx686 device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_stop_streaming(struct imx686 *imx686)
{
	return imx686_write_reg(imx686, IMX686_REG_MODE_SELECT,
				1, IMX686_MODE_STANDBY);
}

/**
 * imx686_set_stream() - Enable sensor streaming
 * @sd: pointer to imx686 subdevice
 * @enable: set to enable sensor streaming
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_set_stream(struct v4l2_subdev *sd, int enable)
{
	struct imx686 *imx686 = to_imx686(sd);
	u32 val = 0;
	int ret;

	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
	mutex_lock(&imx686->mutex);

	if (imx686->streaming == enable) {
		mutex_unlock(&imx686->mutex);
		dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
		return 0;
	}

	if (enable) {
		ret = pm_runtime_resume_and_get(imx686->dev);
		if (ret)
			goto error_unlock;

		ret = imx686_read_reg(imx686, IMX686_REG_FRM_CNT, 1, &val);
		dev_err(imx686->dev, "%s %d frame count %x ret = %d\n", __func__, __LINE__, val, ret);

		ret = imx686_start_streaming(imx686);
		if (ret)
			goto error_power_off;

		dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
	} else {
		val = 0;
		ret = imx686_read_reg(imx686, IMX686_REG_FRM_CNT, 1, &val);
		dev_err(imx686->dev, "%s %d frame count %x ret = %d\n", __func__, __LINE__, val, ret);

		imx686_stop_streaming(imx686);
		pm_runtime_put(imx686->dev);
		dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
	}

	imx686->streaming = enable;

	dev_err(imx686->dev, "%s %d enable %d\n", __func__, __LINE__, enable);
	mutex_unlock(&imx686->mutex);

	return 0;

error_power_off:
	pm_runtime_put(imx686->dev);
error_unlock:
	mutex_unlock(&imx686->mutex);

	return ret;
}

/**
 * imx686_detect() - Detect imx686 sensor
 * @imx686: pointer to imx686 device
 *
 * Return: 0 if successful, -EIO if sensor id does not match
 */
static int imx686_detect(struct imx686 *imx686)
{
	int ret;
	u32 val;

	ret = imx686_read_reg(imx686, IMX686_REG_ID, 2, &val);
	if (ret)
		return ret;

	if (val != IMX686_ID) {
		dev_err(imx686->dev, "chip id mismatch: %x!=%x\n",
			IMX686_ID, val);
		return -ENXIO;
	}

	dev_err(imx686->dev, "%s %d\n", __func__, __LINE__);
	return 0;
}

/**
 * imx686_parse_hw_config() - Parse HW configuration and check if supported
 * @imx686: pointer to imx686 device
 *
 * Return: 0 if successful, error code otherwise.
 */
static int imx686_parse_hw_config(struct imx686 *imx686)
{
	struct fwnode_handle *fwnode = dev_fwnode(imx686->dev);
	struct v4l2_fwnode_endpoint bus_cfg = {
		.bus_type = V4L2_MBUS_CSI2_DPHY
	};
	struct fwnode_handle *ep;
	unsigned long rate;
	unsigned int i;
	int ret;

	if (!fwnode)
		return -ENXIO;

	/* Request optional reset pin */
	imx686->reset_gpio = devm_gpiod_get_optional(imx686->dev, "reset",
						     GPIOD_OUT_LOW);
	if (IS_ERR(imx686->reset_gpio)) {
		dev_err(imx686->dev, "failed to get reset gpio %ld\n",
			PTR_ERR(imx686->reset_gpio));
		return PTR_ERR(imx686->reset_gpio);
	}
	dev_err(imx686->dev, "reset pin available \n");

	/* Request optional enable pin */
	imx686->enable_gpio = devm_gpiod_get_optional(imx686->dev, "enable",
						     GPIOD_OUT_LOW);
	if (IS_ERR(imx686->enable_gpio)) {
		dev_err(imx686->dev, "failed to get enable gpio %ld\n",
			PTR_ERR(imx686->enable_gpio));
		return PTR_ERR(imx686->enable_gpio);
	}
	dev_err(imx686->dev, "enable pin available\n");

	/* Get sensor input clock */
	imx686->inclk = devm_clk_get(imx686->dev, NULL);
	if (IS_ERR(imx686->inclk)) {
		dev_err(imx686->dev, "could not get inclk\n");
		return PTR_ERR(imx686->inclk);
	}
	dev_err(imx686->dev, "inclk available \n");

	rate = clk_get_rate(imx686->inclk);
	if (rate != IMX686_INCLK_RATE) {
		dev_err(imx686->dev, "inclk frequency mismatch\n");
		return -EINVAL;
	}

	/* Get optional DT defined regulators */
	for (i = 0; i < ARRAY_SIZE(imx686_supply_names); i++)
		imx686->supplies[i].supply = imx686_supply_names[i];

	ret = devm_regulator_bulk_get(imx686->dev,
					ARRAY_SIZE(imx686_supply_names),
					imx686->supplies);
	if (ret)
		return ret;

	ep = fwnode_graph_get_next_endpoint(fwnode, NULL);
	if (!ep)
		return -ENXIO;

	bus_cfg.bus_type = V4L2_MBUS_UNKNOWN;

	ret = v4l2_fwnode_endpoint_alloc_parse(ep, &bus_cfg);

	imx686->bus_type = bus_cfg.bus_type;
	if (bus_cfg.bus_type == V4L2_MBUS_CSI2_CPHY) {
		dev_err(imx686->dev, " Bus type is CPHY \n");
	} else if (bus_cfg.bus_type == V4L2_MBUS_CSI2_DPHY) {
		dev_err(imx686->dev, " Bus type is DPHY \n");
	} else {
		dev_err(imx686->dev, " Bus type is %d \n", bus_cfg.bus_type);
		return -ENXIO;
	}
	imx686->bus_type = bus_cfg.bus_type;

	ret = v4l2_fwnode_endpoint_alloc_parse(ep, &bus_cfg);
	fwnode_handle_put(ep);
	if (ret)
		return ret;
	dev_err(imx686->dev,
			"number of CSI2 data lanes %d link frequencies %d\n",
			bus_cfg.bus.mipi_csi2.num_data_lanes,
			bus_cfg.nr_of_link_frequencies);

	// if (bus_cfg.bus.mipi_csi2.num_data_lanes != IMX686_NUM_DATA_LANES) {
	// 	dev_err(imx686->dev,
	// 		"number of CSI2 data lanes %d is not supported\n",
	// 		bus_cfg.bus.mipi_csi2.num_data_lanes);
	// 	// ret = -EINVAL;
	// 	// goto done_endpoint_free;
	// }

	if (!bus_cfg.nr_of_link_frequencies) {
		dev_err(imx686->dev, "no link frequencies defined\n");
		// ret = -EINVAL;
		// goto done_endpoint_free;
	}

	for (i = 0; i < bus_cfg.nr_of_link_frequencies; i++) {
		dev_err(imx686->dev, "i %d freq %llu \n", i, bus_cfg.link_frequencies[i]);
		// if (bus_cfg.link_frequencies[i] == IMX686_LINK_FREQ)
			// goto done_endpoint_free;
	}
	// ret = -EINVAL;

// done_endpoint_free:
	v4l2_fwnode_endpoint_free(&bus_cfg);

	return ret;
}

